use vut_source::Span;
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum TokenKind {
    Identifier,
    Integer,
    Float,
    StringStart,
    StringText,
    StringEnd,
    InterpolationIdentifier,
    InterpolationStart,
    InterpolationEnd,
    LineComment,
    MultiLineComment,
    DocComment,
    Fn,
    Data,
    Interface,
    Enum,
    Type,
    Extern,
    Async,
    Await,
    Static,
    Vut,
    If,
    Elif,
    Else,
    Match,
    For,
    In,
    Break,
    Continue,
    Return,
    Import,
    As,
    At,
    And,
    Or,
    Not,
    True,
    False,
    Null,
    Dyn,
    Opaque,
    Unsafe,
    Plus,
    Minus,
    Star,
    Slash,
    Percent,
    EqualEqual,
    BangEqual,
    Greater,
    Less,
    GreaterEqual,
    LessEqual,
    Equal,
    Colon,
    Arrow,
    FatArrow,
    Range,
    RangeInclusive,
    Ellipsis,
    Question,
    Dot,
    RelativeDots,
    Comma,
    LParen,
    RParen,
    LBracket,
    RBracket,
    AtSign,
    Newline,
    Indent,
    Dedent,
    Eof,
    Error,
}
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct Token {
    pub kind: TokenKind,
    pub span: Span,
}
